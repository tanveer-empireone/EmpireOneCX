<script>
document.addEventListener("scroll", () => {
  const s = document.querySelector(".parallax-wrapper");
  const t = document.querySelector(".fixed-center");
  const r = s.getBoundingClientRect();

  const startOffset = window.innerHeight * 0.2; 
  const endOffset = window.innerHeight * 0.8;   

  if (r.top <= startOffset && r.bottom >= endOffset) {
    t.classList.remove("hide");
    t.style.position = "fixed";
    t.style.top = "50%";
    t.style.left = "50%";
    t.style.transform = "translate(-50%, -50%)";
  } 
  else if (r.bottom < endOffset) {
    t.classList.add("hide");
  } 
  else if (r.top > startOffset) {
    t.classList.add("hide");
  }
});
</script>
    
