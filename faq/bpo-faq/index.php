<script>
(function () {
    window.setTimeout(function () {
        document.querySelectorAll(".bpo-faq-hero__reveal").forEach(function (element) {
            element.classList.add("is-revealed");
        });
    }, 1400);

    const items = Array.from(document.querySelectorAll(".bpo-faq-item"));
    const search = document.getElementById("bpo-faq-search");
    const status = document.getElementById("bpo-faq-search-status");
    const suggestions = document.getElementById("bpo-faq-search-suggestions");
    const empty = document.getElementById("bpo-faq-empty");
    const filters = Array.from(document.querySelectorAll(".bpo-faq-filter"));
    let activeCategory = "All";
    let activeSuggestion = -1;

    function applyFilters() {
        const query = search.value.trim().toLowerCase();
        let visibleCount = 0;
        let firstVisible = null;

        items.forEach(function (item) {
            const categoryMatch = activeCategory === "All" || item.dataset.category === activeCategory;
            const searchMatch = !query || item.dataset.search.includes(query);
            const visible = categoryMatch && searchMatch;
            item.hidden = !visible;
            if (visible) {
                visibleCount += 1;
                if (!firstVisible) firstVisible = item;
            }
        });

        empty.classList.toggle("is-visible", visibleCount === 0);
        status.textContent = query
            ? visibleCount + (visibleCount === 1 ? " matching question found." : " matching questions found.")
            : "";

        if (query && firstVisible) {
            firstVisible.classList.add("is-open");
            firstVisible.querySelector(".bpo-faq-question").setAttribute("aria-expanded", "true");
        }
    }

    function closeSuggestions() {
        suggestions.classList.remove("is-visible");
        search.setAttribute("aria-expanded", "false");
        activeSuggestion = -1;
    }

    function renderSuggestions() {
        const query = search.value.trim().toLowerCase();
        suggestions.replaceChildren();
        activeSuggestion = -1;

        if (query.length < 2) {
            closeSuggestions();
            return;
        }

        const matches = items.filter(function (item) {
            return item.dataset.search.includes(query);
        }).slice(0, 6);

        if (!matches.length) {
            const message = document.createElement("p");
            message.className = "bpo-faq-search-suggestions__empty";
            message.textContent = "No matching questions found.";
            suggestions.appendChild(message);
        } else {
            matches.forEach(function (item, index) {
                const button = document.createElement("button");
                const text = document.createElement("span");
                const title = document.createElement("strong");
                const category = document.createElement("small");
                const icon = document.createElement("i");

                button.type = "button";
                button.className = "bpo-faq-search-suggestion";
                button.setAttribute("role", "option");
                button.dataset.itemIndex = items.indexOf(item);
                button.dataset.suggestionIndex = index;
                title.textContent = item.querySelector(".bpo-faq-question strong").textContent;
                category.textContent = item.dataset.category;
                icon.className = "fa-solid fa-arrow-right";
                icon.setAttribute("aria-hidden", "true");
                text.append(title, category);
                button.append(text, icon);
                suggestions.appendChild(button);
            });
        }

        suggestions.classList.add("is-visible");
        search.setAttribute("aria-expanded", "true");
    }

    function selectSuggestion(button) {
        const item = items[Number(button.dataset.itemIndex)];
        if (!item) return;
        item.hidden = false;
        item.classList.add("is-open");
        item.querySelector(".bpo-faq-question").setAttribute("aria-expanded", "true");
        closeSuggestions();
        item.scrollIntoView({ behavior: "smooth", block: "center" });
        window.setTimeout(function () {
            item.querySelector(".bpo-faq-question").focus({ preventScroll: true });
        }, 500);
    }

    function updateActiveSuggestion(nextIndex) {
        const buttons = Array.from(suggestions.querySelectorAll(".bpo-faq-search-suggestion"));
        if (!buttons.length) return;
        activeSuggestion = (nextIndex + buttons.length) % buttons.length;
        buttons.forEach(function (button, index) {
            button.classList.toggle("is-active", index === activeSuggestion);
            button.setAttribute("aria-selected", index === activeSuggestion ? "true" : "false");
        });
        buttons[activeSuggestion].scrollIntoView({ block: "nearest" });
    }

    document.querySelectorAll(".bpo-faq-question").forEach(function (button) {
        button.addEventListener("click", function () {
            const item = button.closest(".bpo-faq-item");
            const isOpen = item.classList.toggle("is-open");
            button.setAttribute("aria-expanded", isOpen ? "true" : "false");
        });
    });

    filters.forEach(function (button) {
        button.addEventListener("click", function () {
            activeCategory = button.dataset.category;
            filters.forEach(function (filter) {
                filter.classList.toggle("is-active", filter === button);
            });
            applyFilters();
        });
    });

    search.addEventListener("input", function () {
        if (search.value.trim()) {
            activeCategory = "All";
            filters.forEach(function (filter) {
                filter.classList.toggle("is-active", filter.dataset.category === "All");
            });
        }
        applyFilters();
        renderSuggestions();
    });

    search.addEventListener("keydown", function (event) {
        const buttons = Array.from(suggestions.querySelectorAll(".bpo-faq-search-suggestion"));
        if (event.key === "ArrowDown" && buttons.length) {
            event.preventDefault();
            updateActiveSuggestion(activeSuggestion + 1);
        } else if (event.key === "ArrowUp" && buttons.length) {
            event.preventDefault();
            updateActiveSuggestion(activeSuggestion - 1);
        } else if (event.key === "Enter") {
            event.preventDefault();
            if (activeSuggestion >= 0 && buttons[activeSuggestion]) selectSuggestion(buttons[activeSuggestion]);
            else if (buttons[0]) selectSuggestion(buttons[0]);
        } else if (event.key === "Escape") {
            closeSuggestions();
        }
    });

    suggestions.addEventListener("click", function (event) {
        const button = event.target.closest(".bpo-faq-search-suggestion");
        if (button) selectSuggestion(button);
    });

    document.addEventListener("click", function (event) {
        if (!event.target.closest(".bpo-faq-search-wrap")) closeSuggestions();
    });
})();
</script>

